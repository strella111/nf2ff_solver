# -*- coding: utf-8 -*-
"""Единый источник дизайн-токенов приложения.

Все «брендовые» и семантические цвета, типографика и размеры иконок
должны браться отсюда, а не задаваться инлайн в Python или хардкодом в QSS.

Поток использования:
- ``qss_substitutions()`` подставляет токены в ``styles/theme.qss``
  (см. ``app_style.apply_app_theme``);
- ``icon_utils`` читает отсюда цвета и размеры иконок;
- ``far_field_dialog`` и ``near_field_panel`` — цвета трасс, маркеров и фона
  графиков.

Тема одна (светлая). Нейтральные оттенки интерфейса (границы, поверхности)
остаются литералами внутри theme.qss — они не дублируются в Python и не
определяют бренд. Здесь централизованы только реально разделяемые значения.
"""

# --- Акцент (бренд) ---------------------------------------------------------
# Обновлённая палитра — индиго (свежее прежнего синего #2563eb).
ACCENT = '#4f46e5'          # indigo-600
ACCENT_HOVER = '#4338ca'    # indigo-700
ACCENT_PRESSED = '#3730a3'  # indigo-800
ACCENT_FOCUS = '#818cf8'    # indigo-400

# Производные «мягкие» оттенки акцента — для hover/нажатий/выделения.
# Централизованы здесь, чтобы перекрасить весь UI в один тон из одного места.
ACCENT_SOFT = '#eef2ff'         # indigo-50  — фон hover
ACCENT_SOFT_BORDER = '#a5b4fc'  # indigo-300 — граница hover
ACCENT_SOFT_PRESSED = '#e0e7ff' # indigo-100 — фон нажатия
ACCENT_SELECTION = '#e0e7ff'    # выделение строк таблиц/списков
ACCENT_TEXT = '#3730a3'         # текст выбранных элементов (тёмное индиго)
SELECTION_BG = '#dbe2ff'        # selection-background-color текста

# --- Статусы ----------------------------------------------------------------
# Насыщенные цвета для текста и иконок состояний (вердикт маски УБЛ и т.п.).
STATUS_ICON = {
    'ok': '#047857',
    'warning': '#a16207',
    'fail': '#b91c1c',
    'neutral': '#64748b',
}

# --- Иконки -----------------------------------------------------------------
ICON_DEFAULT = '#334155'
ICON_DISABLED = '#94a3b8'
ICON_ON_ACCENT = '#ffffff'   # иконка на кнопке, залитой акцентом (primary)

# Единая шкала размеров. Было три вразнобой (14/16/18) — глифы мельче 16 px
# «замыливаются», а 18 не ложится на сетку иконок 16/20/24.
ICON_SM = 16   # кнопки в панелях и шапке
ICON_MD = 20   # вертикальная панель инструментов графика
ICON_RENDER_SIZES = (16, 20, 24, 32)   # какие размеры кладём в QIcon

# --- График -----------------------------------------------------------------
# Цвета трасс, маркеров и наложений — здесь, а не в far_field_dialog: это
# часть палитры, и разводить коллизии удобнее, видя всё сразу.
PLOT_BG = '#ffffff'          # один фон у обоих видов (был #fbfcff и 'w')
PLOT_TITLE = '#1f2937'
PLOT_AXIS_MUTED = '#64748b'  # правая ось (фаза) — нейтральная

# Тон = плоскость (Az/El), начертание = величина (амплитуда сплошная,
# фаза штриховая и светлее). Раньше фаза была красной и янтарной: красный
# совпадал с маской УБЛ, а пара «зелёный El / красный Az» неразличима при
# дальтонизме. Теперь на графике всего два тона.
TRACE_AZ_AMP = ACCENT
TRACE_EL_AMP = '#059669'      # emerald-600
TRACE_AZ_PHASE = '#818cf8'    # indigo-400
TRACE_EL_PHASE = '#34d399'    # emerald-400

MASK_LINE = '#dc2626'         # предел УБЛ — красный только здесь
MARKER_V = '#111827'
MARKER_H = '#7c3aed'
MARKER_PEAK = '#db2777'

# Наложения («Закрепить»): намеренно вне тонов живых трасс и маркеров,
# иначе закреплённая копия сливалась с текущей кривой.
OVERLAY_COLORS = ('#d97706', '#0891b2', '#a16207', '#475569',
                  '#0f766e', '#b45309', '#334155')

# --- Типографика ------------------------------------------------------------
# Базовый кегль интерфейса. 10pt вместо прежних 9pt для читаемости на стенде.
FONT_SIZE_BASE = '10pt'


def qss_substitutions() -> dict:
    """Плейсхолдеры ``${...}`` → значения для подстановки в theme.qss.

    Ровно то, что тема реально использует: лишние подстановки — та же мёртвая
    ссылка, только незаметная.
    """
    return {
        '${ACCENT}': ACCENT,
        '${ACCENT_HOVER}': ACCENT_HOVER,
        '${ACCENT_PRESSED}': ACCENT_PRESSED,
        '${ACCENT_FOCUS}': ACCENT_FOCUS,
        '${ACCENT_SOFT}': ACCENT_SOFT,
        '${ACCENT_SOFT_BORDER}': ACCENT_SOFT_BORDER,
        '${ACCENT_SOFT_PRESSED}': ACCENT_SOFT_PRESSED,
        '${ACCENT_SELECTION}': ACCENT_SELECTION,
        '${ACCENT_TEXT}': ACCENT_TEXT,
        '${SELECTION_BG}': SELECTION_BG,
        '${FONT_SIZE_BASE}': FONT_SIZE_BASE,
    }
